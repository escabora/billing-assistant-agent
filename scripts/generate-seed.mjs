// ── Event generation ─────────────────────────────────────────────────
const START = new Date("2026-06-01T00:00:00Z");
const END = new Date("2026-09-16T00:00:00Z"); // exclusive; "today" in the demo
const SAMPLES_PER_DAY = 4; // metering pipeline flushes every 6h

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [];
lines.push("-- GENERATED by scripts/generate-seed.mjs — do not edit by hand.");
lines.push(
  "DELETE FROM invoice_lines; DELETE FROM invoices; DELETE FROM usage_events;"
);
lines.push(
  "DELETE FROM customers; DELETE FROM plan_prices; DELETE FROM skus; DELETE FROM plans;"
);

for (const p of plans)
  lines.push(
    `INSERT INTO plans VALUES (${q(p.id)}, ${q(p.name)}, ${p.base_fee_cents});`
  );
for (const s of skus)
  lines.push(
    `INSERT INTO skus VALUES (${q(s.id)}, ${q(s.name)}, ${q(s.unit)}, ${s.unit_size}, ${q(s.aggregation)});`
  );
for (const [plan, prices] of Object.entries(planPrices))
  for (const [sku, [inc, price]] of Object.entries(prices))
    lines.push(
      `INSERT INTO plan_prices VALUES (${q(plan)}, ${q(sku)}, ${inc}, ${price});`
    );
for (const c of customers)
  lines.push(
    `INSERT INTO customers VALUES (${q(c.id)}, ${q(c.name)}, ${q(c.plan_id)}, 'USD', ${q(c.created_at)});`
  );

let eventCount = 0;
const eventRows = [];
for (const c of customers) {
  let dayIndex = 0;
  for (
    let d = new Date(START);
    d < END;
    d.setUTCDate(d.getUTCDate() + 1), dayIndex++
  ) {
    const dayStr = d.toISOString().slice(0, 10);
    const dow = d.getUTCDay();
    const weekend = dow === 0 || dow === 6 ? 0.55 : 1;
    const growth = c.growth ? Math.pow(1 + c.growth, dayIndex) : 1;
    const spike = c.spikeDays?.includes(dayStr) ? 6 : 1;

    for (const sku of skus) {
      if (sku.id === "r2_storage_gb_month") {
        // Storage is sampled once a day as GB stored; the rating engine
        // turns daily GB samples into GB-months (avg over the month).
        const gb = jitter(
          c.r2_gb * (c.growth ? Math.pow(1.004, dayIndex) : 1),
          0.02
        );
        eventRows.push([
          `${c.id}:${sku.id}:${dayStr}`,
          c.id,
          sku.id,
          gb,
          `${dayStr}T23:59:00Z`,
          "r2-metering"
        ]);
        continue;
      }
      const base = c.daily[sku.id];
      if (!base) continue;
      const aiGrowth = sku.id === "ai_neurons" ? growth : 1;
      const dayTotal = base * weekend * spike * aiGrowth;
      for (let s = 0; s < SAMPLES_PER_DAY; s++) {
        const qty = Math.max(0, jitter(dayTotal / SAMPLES_PER_DAY, 0.25));
        const hh = String(s * 6).padStart(2, "0");
        eventRows.push([
          `${c.id}:${sku.id}:${dayStr}:${s}`,
          c.id,
          sku.id,
          qty,
          `${dayStr}T${hh}:00:00Z`,
          sku.id.startsWith("r2")
            ? "r2-metering"
            : sku.id === "ai_neurons"
              ? "ai-gateway"
              : "workers-metering"
        ]);
      }
    }
  }
}

// Batch inserts (D1 handles multi-row VALUES fine; keep batches modest).
const BATCH = 200;
for (let i = 0; i < eventRows.length; i += BATCH) {
  const chunk = eventRows.slice(i, i + BATCH);
  const values = chunk
    .map(
      ([k, cu, sk, qty, at, src]) =>
        `(${q(k)}, ${q(cu)}, ${q(sk)}, ${qty}, ${q(at)}, ${q(src)})`
    )
    .join(",\n  ");
  lines.push(
    `INSERT INTO usage_events (idempotency_key, customer_id, sku_id, quantity, occurred_at, source) VALUES\n  ${values};`
  );
  eventCount += chunk.length;
}

mkdirSync("seed", { recursive: true });
writeFileSync("seed/seed.sql", lines.join("\n") + "\n");
console.log(
  `seed/seed.sql written: ${customers.length} customers, ${eventCount} usage events`
);
